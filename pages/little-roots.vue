<script setup>
import { ref } from 'vue'

useHead({ 
  title: 'Little Roots — Homeschool Circle | Mawun Valley Farm',
  meta: [
    { name: 'description', content: 'A weekly gathering for homeschooling families. 6 children, ages 6-7, building friendships through play, sports, and creativity at Mawun Valley Farm.' }
  ]
})

const form = ref({
  parentNames: '',
  whatsapp: '',
  email: '',
  location: '',
  childName: '',
  childAge: '',
  homeschoolDuration: '',
  aboutChild: '',
  whyInterested: '',
  canCommit: '',
  parentPresent: '',
  additionalNotes: '',
  understood: false
})

const submitting = ref(false)
const submitSuccess = ref(false)
const submitError = ref(false)

const submitApplication = async () => {
  submitting.value = true
  submitSuccess.value = false
  submitError.value = false

  const webhookUrl = 'https://discord.com/api/webhooks/1478653783176384674/SBAkObBUEUU9yNlnXjcnWdiInFoohTgi9jlNHgItjSYfQyWw-m0o0PjzKRnwFscP65pA'

  const embed = {
    title: '🌱 New Little Roots Application',
    color: 0x7A8B6F,
    fields: [
      { name: '👨‍👩‍👧 Parent(s)', value: form.value.parentNames, inline: true },
      { name: '📱 WhatsApp', value: form.value.whatsapp, inline: true },
      { name: '📧 Email', value: form.value.email || 'Not provided', inline: true },
      { name: '📍 Location', value: form.value.location, inline: true },
      { name: '👦 Child', value: `${form.value.childName} (${form.value.childAge} years)`, inline: true },
      { name: '📚 Homeschooling', value: form.value.homeschoolDuration, inline: true },
      { name: '💬 About Child', value: form.value.aboutChild },
      { name: '❓ Why Interested', value: form.value.whyInterested },
      { name: '📅 Can Commit Wednesdays', value: form.value.canCommit, inline: true },
      { name: '👨‍👩‍👧 Parent Present', value: form.value.parentPresent, inline: true },
      { name: '📝 Additional Notes', value: form.value.additionalNotes || 'None' }
    ],
    timestamp: new Date().toISOString()
  }

  try {
    const response = await fetch(webhookUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ embeds: [embed] })
    })

    if (response.ok) {
      submitSuccess.value = true
      form.value = {
        parentNames: '', whatsapp: '', email: '', location: '',
        childName: '', childAge: '', homeschoolDuration: '', aboutChild: '',
        whyInterested: '', canCommit: '', parentPresent: '', additionalNotes: '',
        understood: false
      }
    } else {
      submitError.value = true
    }
  } catch (error) {
    submitError.value = true
  }

  submitting.value = false
}
</script>

